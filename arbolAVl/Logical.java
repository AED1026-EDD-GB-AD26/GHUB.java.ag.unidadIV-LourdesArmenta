package arbolAVl;
/*
Determinar si se debe cambiar la altura a un nodo
 */

public class Logical {
    //atributo
    boolean v;
    //constructor
    public Logical(boolean f) {
        v = f;
    }
    //setter
    public void setLogical(boolean f){
        v = f;
    }
    //getter
    public boolean booleanValue(){
        return v;
    }
 
}